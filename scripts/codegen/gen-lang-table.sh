#!/usr/bin/env bash
# Regenerate src/scanner/lang_table.rs from Debian's iso-codes data:
# every ISO 639-2 code (terminology and bibliographic) that has an
# ISO 639-1 equivalent, which is what Plex stores for stream languages.
# Usage: gen-lang-table.sh [iso_639-2.json]
set -euo pipefail
cd "$(dirname "$0")/../.."

SRC="${1:-$(nix build --no-link --print-out-paths nixpkgs#isocodes)/share/iso-codes/json/iso_639-2.json}"
OUT=src/scanner/lang_table.rs

{
  echo "// Generated by scripts/codegen/gen-lang-table.sh from iso-codes; do not edit."
  echo
  echo "/// ISO 639-2 (T and B) to ISO 639-1, sorted for binary search."
  echo "pub(super) const ISO639_2_TO_1: &[(&str, &str)] = &["
  jq -r '."639-2"[] | select(.alpha_2 != null)
         | ([.alpha_3] + (if .bibliographic then [.bibliographic] else [] end))[] as $three
         | "\($three)\t\(.alpha_2)"' "$SRC" \
    | LC_ALL=C sort -u \
    | awk -F'\t' '{ printf "    (\"%s\", \"%s\"),\n", $1, $2 }'
  echo "];"
} > "$OUT"
echo "wrote $(grep -c '^    (' "$OUT") entries to $OUT"
