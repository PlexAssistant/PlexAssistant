#!/usr/bin/env bash
# Regenerate src/localize/tag_table.rs from a JSON object of English labels
# to Chinese. The default input is the genre table shipped with
# chinese-localization-for-plex, plus the mood and style labels that table
# does not carry.
# Usage: gen-tag-table.sh [tags.json]
set -euo pipefail
cd "$(dirname "$0")/../.."

SRC="${1:-scripts/codegen/tags.json}"
OUT=src/localize/tag_table.rs

{
  echo "// Generated by scripts/codegen/gen-tag-table.sh; do not edit."
  echo
  echo "/// English genre, mood and style labels to Chinese, sorted for binary search."
  echo "pub(super) const LABELS: &[(&str, &str)] = &["
  jq -r 'to_entries[] | "\(.key)\t\(.value)"' "$SRC" \
    | LC_ALL=C sort -u \
    | awk -F'\t' '{
        gsub(/\\/, "\\\\", $1); gsub(/"/, "\\\"", $1)
        gsub(/\\/, "\\\\", $2); gsub(/"/, "\\\"", $2)
        printf "    (\"%s\", \"%s\"),\n", $1, $2
      }'
  echo "];"
} > "$OUT"
echo "wrote $(grep -c '^    (' "$OUT") entries to $OUT"
